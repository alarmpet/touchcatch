import fs from 'node:fs/promises';
import path from 'node:path';

function toCamelCase(key) {
  return key.replace(/-([a-z0-9])/g, (_, g) => g.toUpperCase());
}

export async function generateMobileRegistry() {
  const catalogPath = 'content/learning/catalog.v1.json';
  const catalogBuf = await fs.readFile(catalogPath, 'utf-8');
  const catalog = JSON.parse(catalogBuf);

  const draftFiles = await fs.readdir('content/learning/drafts');
  const availableKeys = new Set(draftFiles.filter(f => f.endsWith('.json')).map(f => f.replace('.json', '')));

  const imports = [];
  const entries = [];

  for (const entry of catalog.entries) {
    if (!availableKeys.has(entry.key)) continue;

    const varName = toCamelCase(entry.key);
    imports.push(`const ${varName} = require('../../../../content/learning/drafts/${entry.key}.json') as unknown as Bundle;`);
    
    const category = entry.category || 'ENGLISH';
    entries.push(`  buildDemoEntry('${category}', ${varName}, { imageA: require('../../../../content/learning/source/${entry.key}-a.png'), imageB: require('../../../../content/learning/source/${entry.key}-b.png') }),`);
  }

  const code = `// GENERATED CODE - DO NOT EDIT MANUALLY
// Generated by tools/content/generate-registry.js

import { Bundle, DemoEntry } from './types';

function buildDemoEntry(
  category: 'ENGLISH' | 'GENERAL_KNOWLEDGE' | 'KOREAN_PROVERB' | 'KOREAN_IDIOM',
  bundle: Bundle,
  assets: { imageA: number; imageB: number }
): DemoEntry {
  return {
    id: bundle.id,
    key: bundle.key,
    category,
    difficulty: bundle.difficulty,
    sceneBrief: bundle.sceneBrief,
    meaning: bundle.meaning,
    wordHunts: bundle.wordHunts,
    suddenDeath: bundle.suddenDeath,
    imageA: assets.imageA,
    imageB: assets.imageB,
    bundle,
  };
}

${imports.join('\n')}

// DEV-only registry: private solutions never cross a network or production API boundary.
export const learningDemoEntries: DemoEntry[] = [
${entries.join('\n')}
];
`;

  const outputPath = 'apps/mobile/src/learning-demo/registry.ts';
  await fs.writeFile(outputPath, code, 'utf-8');
  console.log(`[REGISTRY GENERATED] ${entries.length} entries written to ${outputPath}`);
}

if (process.argv[1].endsWith('generate-registry.js')) {
  await generateMobileRegistry();
}
